// Writes docs/GLOSSARY_REVIEW.md: every rendering in each supported language in
// glossary/domains that is not yet marked "reviewed": true, grouped by domain.
// Run with: npm run glossary:review
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

// The supported languages, from the defaultLanguage setting in package.json.
const setting = JSON.parse(readFileSync('package.json', 'utf8')).contributes.configuration.properties['bhashabridge.defaultLanguage'];
const languages = setting.enum.map((code, i) => ({ code, name: setting.enumItemLabels[i] }));

const folder = 'glossary/domains';
const lines = [
  '# Glossary review',
  '',
  `${languages.map(l => l.name).join(' and ')} renderings still to review. Generated by \`npm run glossary:review\`; do not edit this file.`,
  '',
  'Until a rendering is marked reviewed, BhashaBridge does not show it: the term simply stays in English.',
  '',
  'To review: open the domain file named in each heading, fix the text if needed, and mark it reviewed: `"reviewed": true` when every language in the entry is right, or a list such as `"reviewed": ["gu"]` for some of them.',
  'Then run `npm run glossary:review` again and this list gets shorter.',
  '',
  '- **annotate**: the English term stays and the meaning is added after its first use, e.g. "ledger (ખાતાવહી)". The meaning should be short and plain.',
  '- **translate**: the term itself is replaced by the rendering.',
  '',
];

let total = 0;
for (const file of readdirSync(folder).filter(f => f.endsWith('.json')).sort()) {
  const domain = JSON.parse(readFileSync(join(folder, file), 'utf8'));
  const rows = [];
  for (const kind of ['annotate', 'translate']) {
    for (const [term, entry] of Object.entries(domain[kind] ?? {})) {
      const reviewed = entry.reviewed === true ? languages.map(l => l.code) : Array.isArray(entry.reviewed) ? entry.reviewed : [];
      const pending = languages.filter(l => entry[l.code] !== undefined && !reviewed.includes(l.code));
      if (pending.length > 0) {
        rows.push(`| ${term} | ${kind} | ${languages.map(l => (pending.includes(l) ? entry[l.code] : entry[l.code] === undefined ? '' : '✓ reviewed')).join(' | ')} |`);
      }
    }
  }
  if (rows.length > 0) {
    total += rows.length;
    lines.push(`## ${domain.label} (\`${folder}/${file}\`)`, '', `| Term | Kind | ${languages.map(l => l.name).join(' | ')} |`, `|---|---|${languages.map(() => '---|').join('')}`, ...rows, '');
  }
}

lines.splice(3, 0, '', `**${total} renderings to review.**`);
writeFileSync('docs/GLOSSARY_REVIEW.md', lines.join('\n'));
console.log(`docs/GLOSSARY_REVIEW.md: ${total} renderings to review.`);
